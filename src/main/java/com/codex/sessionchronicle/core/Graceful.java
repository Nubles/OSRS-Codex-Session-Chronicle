	/** Marks of grace for the whole outfit, as the wiki's Graceful outfit page gives it: 260. */
	public static final int SET_COST = 260;

	private static final Map<Integer, Graceful> BY_ID = new HashMap<>();

	static
	{
		for (Graceful piece : values())
		{
			for (int id : piece.ids)
			{
				BY_ID.put(id, piece);
			}
		}
	}

	private final String label;
	private final int cost;
	/** The plain piece, for its picture. */
	private final int iconId;
	private final int[] ids;

	Graceful(String label, int cost, int iconId, int... ids)
	{
		this.label = label;
		this.cost = cost;
		this.iconId = iconId;
		this.ids = ids;
	}

	public String getLabel()
	{
		return label;
	}

	public int getCost()
	{
		return cost;
	}

	public int getIconId()
	{
		return iconId;
	}

	/** The piece this item is, in any colour, or null. */
	public static Graceful of(int itemId)
	{
		return BY_ID.get(itemId);
	}

	/** The pieces among these items. */
	public static Set<Graceful> among(Collection<Integer> itemIds)
	{
		Set<Graceful> found = EnumSet.noneOf(Graceful.class);
		for (int id : itemIds)
		{
			Graceful piece = of(id);
			if (piece != null)
			{
				found.add(piece);
			}
		}
		return found;
	}

	/** Marks still to buy the pieces not owned. */
	public static int costOfMissing(Set<Graceful> owned)
	{
		int total = 0;
		for (Graceful piece : values())
		{
			if (owned == null || !owned.contains(piece))
			{
				total += piece.cost;
			}
		}
		return total;
	}
